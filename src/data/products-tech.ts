export const techProducts: Product[] = seeds.map((s, i) => {
  const badges: ProductBadgeType[] = [...(s.badges ?? [])];
  if (s.compareAt && !badges.includes("promo")) badges.push("promo");
  return {
    id: `p-${s.slug}`,
    slug: s.slug,
    name: s.name,
    categoryId: s.categoryId,
    group: s.group,
    platforms: [],
    condition: s.condition ?? "neuf",
    price: s.price,
    compareAtPrice: s.compareAt,
    stockStatus: s.stock ?? "en_stock",
    stockLeft: s.stockLeft,
    images: [`/products/${s.image}.webp`],
    badges,
    shortDescription: s.short,
    description: s.description,
    compatibility: s.compatibility,
    includes: s.includes,
    isFeatured: s.featured,
    warranty: true,
    createdAt: `2026-11-${String(10 - (i % 9)).padStart(2, "0")}`,
  } as Product;
});
